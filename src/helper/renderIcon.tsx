// تابع دریافت آیکون
export const getIcon = (iconName: string): React.ElementType | null => {
  const IconComponent = iconMap[iconName as keyof typeof iconMap];
  if (!IconComponent) {
    console.warn(`آیکون "${iconName}" یافت نشد`);
    return null;
  }
  return IconComponent as React.ElementType;
};

// تابع رندر آیکون با کلاس‌های دلخواه
export const renderIcon = (iconName: string, className: string = "w-5 h-5") => {
  const Icon = getIcon(iconName);
  if (!Icon) return null;
  return <Icon className={className} />;
};

// لیست تمام آیکون‌های موجود برای استفاده
export const availableIcons = Object.keys(iconMap);

// تابع بررسی وجود آیکون
export const hasIcon = (iconName: string): boolean => {
  return iconName in iconMap;
};

// تابع دریافت آیکون با fallback
export const getIconSafe = (iconName: string, fallbackIcon: React.ElementType = Home): React.ElementType => {
  const Icon = getIcon(iconName);
  return Icon || fallbackIcon;
};

// تابع رندر آیکون با fallback
export const renderIconSafe = (
  iconName: string, 
  className: string = "w-5 h-5", 
  fallbackClassName: string = "w-5 h-5"
) => {
  const Icon = getIcon(iconName);
  if (!Icon) {
    const FallbackIcon = Home;
    return <FallbackIcon className={fallbackClassName} />;
  }
  return <Icon className={className} />;
};

